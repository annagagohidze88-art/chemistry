export const SCHOOL_ELEMENT_NUMBERS = Object.keys(SCHOOL_ELEMENT_RIDDLES).map(Number);

export interface FormattedClue {
  id: number;
  tag: string;
  title: string;
  content: string;
  hintLevel: 'easy' | 'medium' | 'direct';
}

/**
 * აბრუნებს 6 გასაგებ, ლოგიკურ და ეტაპობრივ მინიშნებას ნებისმიერი ელემენტისთვის
 */
export function getElementRiddleClues(element: ChemicalElement): FormattedClue[] {
  const customRiddle = SCHOOL_ELEMENT_RIDDLES[element.atomicNumber];

  if (customRiddle) {
    return [
      {
        id: 1,
        tag: 'ყოველდღიურობა & ბუნება',
        title: 'სად გვხვდება და რაში ვიყენებთ?',
        content: customRiddle.everydayHint,
        hintLevel: 'easy',
      },
      {
        id: 2,
        tag: 'გარეგნობა & ფიზიკური ნიშანი',
        title: 'როგორ გამოიყურება?',
        content: customRiddle.lookAndState,
        hintLevel: 'easy',
      },
      {
        id: 3,
        tag: 'საიდუმლო თვისება',
        title: 'განსაკუთრებული „სუპერძალა“',
        content: customRiddle.superpower,
        hintLevel: 'medium',
      },
      {
        id: 4,
        tag: 'პერიოდული სისტემა',
        title: 'მდებარეობა ცხრილში',
        content: customRiddle.periodicLocation,
        hintLevel: 'medium',
      },
      {
        id: 5,
        tag: 'ატომური მონაცემები',
        title: 'ნომერი და მასის დიაპაზონი',
        content: customRiddle.atomicClue,
        hintLevel: 'direct',
      },
      {
        id: 6,
        tag: 'პირდაპირი მინიშნება',
        title: 'პირველი ასო & სიმბოლო',
        content: customRiddle.letterClue,
        hintLevel: 'direct',
      },
    ];
  }

  // Fallback გენერატორი ნებისმიერი სხვა ელემენტისთვის
  const phaseKa =
    element.phase === 'gas'
      ? 'აირადი ნივთიერება (აირი)'
      : element.phase === 'liquid'
      ? 'თხევადი ნივთიერება (სითხე)'
      : 'მყარი ნივთიერება';

  const categoryName = CATEGORIES[element.category]?.nameKa || element.category;

  const everyday =
    element.uses && element.uses.length > 0
      ? `გამოიყენება შემდეგ სფეროებში: ${element.uses.slice(0, 3).join(', ')}.`
      : element.summary || 'გამოიყენება სამეცნიერო და ტექნოლოგიურ კვლევებში.';

  const appearanceDesc =
    element.appearance && element.appearance.length > 3
      ? `${element.appearance}. ოთახის ტემპერატურაზე წარმოადგენს: ${phaseKa}.`
      : `ოთახის ტემპერატურაზე (20 °C) წარმოადგენს: ${phaseKa}.`;

  const groupDesc = element.group ? `ჯგუფი ${element.group}` : 'ლანთანოიდების / აქტინოიდების ოჯახი';

  return [
    {
      id: 1,
      tag: 'გამოყენების სფერო',
      title: 'სად გამოიყენება?',
      content: everyday,
      hintLevel: 'easy',
    },
    {
      id: 2,
      tag: 'გარეგნობა & მდგომარეობა',
      title: 'როგორ გამოიყურება?',
      content: appearanceDesc,
      hintLevel: 'easy',
    },
    {
      id: 3,
      tag: 'ქიმიური ოჯახი',
      title: 'რომელ კლასს ეკუთვნის?',
      content: `მიეკუთვნება ჯგუფს: ${categoryName}. ვალენტობა: ${element.valency}.`,
      hintLevel: 'medium',
    },
    {
      id: 4,
      tag: 'პერიოდული სისტემა',
      title: 'მდებარეობა ცხრილში',
      content: `პერიოდი: ${element.period}, ${groupDesc}, ${element.block}-ბლოკის ელემენტი.`,
      hintLevel: 'medium',
    },
    {
      id: 5,
      tag: 'ატომური მონაცემები',
      title: 'ატომური ნომერი და მასა',
      content: `ატომური ნომერი Z = ${element.atomicNumber}, ფარდობითი ატომური მასა Ar ≈ ${parseFloat(element.atomicMass).toFixed(1)}.`,
      hintLevel: 'direct',
    },
    {
      id: 6,
      tag: 'პირდაპირი მინიშნება',
      title: 'პირველი ასო & სიმბოლო',
      content: `ქართული სახელი იწყება ასო „${element.nameKa.charAt(0)}“-ზე, ქიმიური სიმბოლოა: ${element.symbol}`,
      hintLevel: 'direct',
    },
  ];
}
